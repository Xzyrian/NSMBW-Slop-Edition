#!/usr/bin/env python3
"""build_smb3.py - SMB3Disassembly -> out/: the recompiled game, ready to compile.

  1. assemble smb3.asm with NESASM (nesasm.exe here on Windows; elsewhere $NESASM or nesasm on
     PATH), with a listing (-l 3 -m)
  2. check the ROM against the original (SMB3 USA Rev A, MD5 86d1982f...); a changed disassembly
     is fine, it is only reported
  3. recompile: tools/recomp6502.py -> out/smb3_bNN.c, out/smb3_table.c
  4. out/smb3_rom.c: the ROM image (the game's data; the code reads its tables from it)
  5. out/smb3_raccoon_anm.c: NSMB2's Raccoon animations as NSMBW's (tools/nsmb2_anims.py), from
     the user's NSMB2 RomFS dump in ../NSMB2_RomFS (none there: an empty archive)
Everything it writes is in out/. Skipped when nothing it depends on changed (out/.stamp). recomp/build.py runs it."""
import hashlib, os, shutil, subprocess, sys, glob
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, 'out')
ORIGINAL_MD5 = '86d1982fea7342c0af9679ddf3869d8d'

def inputs():
    fs = [os.path.join(ROOT, 'smb3.asm'), os.path.join(HERE, 'recomp6502.py'), os.path.abspath(__file__), os.path.join(ROOT, 'port', 'hooks.txt')]
    for pat in ('PRG/*.asm', 'PRG/*/*.asm', 'PRG/*/*/*.asm', 'CHR/*.pcx'): fs += glob.glob(os.path.join(ROOT, pat))
    return sorted(fs)

def stamp():
    h = hashlib.sha1()
    for f in inputs():
        if not os.path.exists(f): continue
        h.update(f.encode()); h.update(open(f, 'rb').read())
    return h.hexdigest()

def nesasm():
    if os.environ.get('NESASM'): return os.environ['NESASM']
    exe = os.path.join(ROOT, 'nesasm.exe')
    if os.name == 'nt' and os.path.exists(exe): return exe
    return shutil.which('nesasm') or shutil.which('nesasm3') or sys.exit('build_smb3: no NESASM (set NESASM=path)')

def raccoon_anims():
    romfs = os.path.join(os.path.dirname(ROOT), 'NSMB2_RomFS')
    src = os.path.join(romfs, 'Model', 'Player', 'Anim_Common.bcres')
    tool = os.path.join(HERE, 'nsmb2_anims.py'); out_c = os.path.join(OUT, 'smb3_raccoon_anm.c')
    pose = os.path.join(os.path.dirname(ROOT), 'models', 'frog', 'frog_idle_pose.json')   # (the Frog's idle: F_wait)
    newest = max(os.path.getmtime(f) for f in (tool, src, pose) if os.path.exists(f))
    if os.path.exists(out_c) and os.path.getmtime(out_c) >= newest: return
    subprocess.run([sys.executable, tool, romfs, os.path.join(OUT, 'smb3_raccoon_anm.brres'), out_c], check=True)

def main():
    os.makedirs(OUT, exist_ok=True)
    raccoon_anims()
    st = stamp(); sp = os.path.join(OUT, '.stamp')
    if os.path.exists(sp) and open(sp).read().strip() == st and os.path.exists(os.path.join(OUT, 'smb3_rom.c')):
        print('SMB3: up to date'); return
    print('SMB3: assembling...')
    # (assembled in out/, its includes found through NES_INCLUDE: nothing is written or deleted
    #  in the disassembly's own folder)
    with open(os.path.join(OUT, '_smb3_build.asm'), 'w', newline='\n') as f:
        f.write('\t.list\n\t.mlist\n' + open(os.path.join(ROOT, 'smb3.asm'), encoding='latin1').read())
    env = dict(os.environ, NES_INCLUDE=ROOT)
    r = subprocess.run([nesasm(), '-l', '3', '-m', '_smb3_build.asm'], cwd=OUT, env=env, capture_output=True, text=True, errors='replace')
    if r.returncode or 'error' in (r.stdout + r.stderr).lower() or not os.path.exists(os.path.join(OUT, '_smb3_build.nes')):
        sys.exit('build_smb3: NESASM failed:\n' + r.stdout[-2000:] + r.stderr[-2000:])
    for ext in ('nes', 'lst'): os.replace(os.path.join(OUT, '_smb3_build.' + ext), os.path.join(OUT, 'smb3.' + ext))
    rom = open(os.path.join(OUT, 'smb3.nes'), 'rb').read()
    md5 = hashlib.md5(rom).hexdigest()
    print('SMB3: ROM %s' % ('= the original (USA Rev A)' if md5 == ORIGINAL_MD5 else 'MODIFIED (md5 %s)' % md5))
    print('SMB3: recompiling...')
    subprocess.run([sys.executable, os.path.join(HERE, 'recomp6502.py'), os.path.join(OUT, 'smb3.nes'), os.path.join(OUT, 'smb3.lst'), OUT,
                    '--hooks', os.path.join(ROOT, 'port', 'hooks.txt'), '--symbols', os.path.join(OUT, '_smb3_build.fns')], check=True)
    with open(os.path.join(OUT, 'smb3_rom.c'), 'w', newline='\n') as f:
        f.write('/* generated by tools/build_smb3.py: the ROM assembled from the disassembly */\n#include <stdint.h>\n')
        f.write('const uint32_t smb3_rom_size = %d;\nconst uint8_t smb3_rom[%d] = {\n' % (len(rom), len(rom)))
        for i in range(0, len(rom), 32): f.write(','.join(str(b) for b in rom[i:i + 32]) + ',\n')
        f.write('};\n')
    open(sp, 'w').write(st)
    print('SMB3: done -> %s' % OUT)

if __name__ == '__main__': main()
