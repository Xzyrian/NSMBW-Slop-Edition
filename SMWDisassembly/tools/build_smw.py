#!/usr/bin/env python3
"""build_smw.py - SMWDisassembly -> out/: the recompiled game, ready to compile.

  1. assemble smw.asm (the USA version) with Asar 1.91 (asar.exe here on Windows; elsewhere
     $ASAR or asar on PATH), with a WLA symbol file - its [addr-to-line mapping] says which
     bytes each source line made
  2. check the ROM against the original (Super Mario World USA, SHA-1 6b47bb75...); a changed
     disassembly is fine, it is only reported
  3. recompile: tools/recomp65816.py -> out/smw_bNN.c, smw_interp.c, smw_table.c, smw_syms.h
  4. out/smw_rom.c: the ROM image (the game's data; the code reads its tables from it)
Everything it writes is in out/ (Asar's output goes there too: nothing is written in the
disassembly's own folder). Skipped when nothing it depends on changed (out/.stamp); when out/ is
complete and Asar isn't there, what's in out/ is used. recomp/build.py runs it."""
import glob, hashlib, os, shutil, subprocess, sys
HERE = os.path.dirname(os.path.abspath(__file__))
ROOT = os.path.dirname(HERE)
OUT = os.path.join(ROOT, 'out')
ORIGINAL_SHA1 = '6b47bb75d16514b6a476aa0c73a683a2a4c18765'

def inputs():
    fs = [os.path.join(HERE, 'recomp65816.py'), os.path.abspath(__file__), os.path.join(ROOT, 'port', 'hooks.txt')]
    for pat in ('*.asm', 'lvl/*.asm', 'lvl/*/*.asm', 'gfx/*/*', 'col/*/*', 'samples/*', 'sfx/*', 'empty/*'): fs += glob.glob(os.path.join(ROOT, pat))
    return sorted(fs)

def stamp():
    h = hashlib.sha1()
    for f in inputs():
        if not os.path.isfile(f): continue
        h.update(os.path.relpath(f, ROOT).replace('\\', '/').encode()); h.update(open(f, 'rb').read())
    return h.hexdigest()

def asar():
    if os.environ.get('ASAR'): return os.environ['ASAR']
    exe = os.path.join(ROOT, 'asar.exe')
    if os.name == 'nt' and os.path.exists(exe): return exe
    return shutil.which('asar')

def main():
    os.makedirs(OUT, exist_ok=True)
    st = stamp(); sp = os.path.join(OUT, '.stamp')
    done = os.path.exists(os.path.join(OUT, 'smw_rom.c')) and os.path.exists(os.path.join(OUT, 'smw_table.c'))
    if done and os.path.exists(sp) and open(sp).read().strip() == st:
        print('SMW: up to date'); return
    a = asar()
    if not a:
        if done: print('SMW: no Asar (asar.exe / $ASAR): using out/ as it is'); return
        sys.exit('build_smw: no Asar 1.91 (put asar.exe in SMWDisassembly, or set ASAR=path)')
    print('SMW: assembling...')
    rom_p, sym_p = os.path.join(OUT, 'smw.sfc'), os.path.join(OUT, 'smw.sym')
    for p in (rom_p, sym_p):
        if os.path.exists(p): os.remove(p)
    r = subprocess.run([a, '-wno1009', '-wno1018', '--fix-checksum=off', '--symbols=wla', '--symbols-path=' + sym_p,
                        '--define', '_VER=!__VER_U', 'smw.asm', rom_p], cwd=ROOT, capture_output=True, text=True, errors='replace')
    if r.returncode or not os.path.exists(rom_p):
        sys.exit('build_smw: Asar failed:\n' + r.stdout[-2000:] + r.stderr[-2000:])
    rom = open(rom_p, 'rb').read()
    if len(rom) % 0x8000 == 512: rom = rom[512:]; open(rom_p, 'wb').write(rom)
    sha = hashlib.sha1(rom).hexdigest()
    print('SMW: ROM %s' % ('= the original (USA)' if sha == ORIGINAL_SHA1 else 'MODIFIED (sha1 %s)' % sha))
    print('SMW: recompiling...')
    subprocess.run([sys.executable, os.path.join(HERE, 'recomp65816.py'), rom_p, sym_p, ROOT, OUT,
                    '--hooks', os.path.join(ROOT, 'port', 'hooks.txt')], check=True)
    with open(os.path.join(OUT, 'smw_rom.c'), 'w', newline='\n') as f:
        f.write('/* generated by tools/build_smw.py: the ROM assembled from the disassembly */\n#include <stdint.h>\n')
        f.write('const uint32_t smw_rom_size = %d;\nconst uint8_t smw_rom[%d] = {\n' % (len(rom), len(rom)))
        for i in range(0, len(rom), 32): f.write(','.join(str(b) for b in rom[i:i + 32]) + ',\n')
        f.write('};\n')
    open(sp, 'w').write(st)
    print('SMW: done -> %s' % OUT)

if __name__ == '__main__': main()
