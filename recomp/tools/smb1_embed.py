#!/usr/bin/env python3
"""Retro Mario (SMB1): Super Mario Bros.' ROM and its symbols, for the runtime.

    python3 tools/smb1_embed.py [SMB1Disassembly dir] [out dir]

From SMB1Disassembly (the user's MMC3 build of the SMB disassembly, assembled with asm6:
build.bat -> SMBBase.nes and its listing list.txt) this writes
  out/smb1_rom.c   - the ROM's bytes (smb1_rom[], smb1_rom_size; empty when there is no ROM)
  out/smb1_syms.h  - the addresses the runtime uses, from the listing and the sources
                     (and the build's switches, code/settings*.asm: SMB1_CFG_<name>):
                     SMB1_<name> for RAM (zero page and $0100-$07FF, .enum'd or `name = $xxxx`)
                     and code labels, SMB1_<name>_BANK for code ($8000-$BFFF: its 16 KB bank;
                     $C000-$FFFF: -1, the fixed bank)
The runtime (runtime/smb1_mario.c) runs SMB1's own routines from it. Nothing is written when
both files are up to date (same ROM, same listing).
"""
import os, re, sys, hashlib

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SRC = sys.argv[1] if len(sys.argv) > 1 else os.path.join(os.path.dirname(ROOT), 'SMB1Disassembly')
OUT = sys.argv[2] if len(sys.argv) > 2 else os.path.join(ROOT, 'out')
NEEDED = ['PlayerMovementSubs', 'PlayerGfxHandler', 'SoundEngine', 'Player_State', 'Player_X_Speed',
          'SavedJoypadBits', 'Sprite_Data', 'Timers', 'PlayerSize']


def read(p):
    with open(p, 'rb') as f: return f.read()


def symbols(src):
    syms = {}
    lst = os.path.join(src, 'list.txt')
    bank = None
    if os.path.exists(lst):
        for line in open(lst, encoding='latin-1'):
            m = re.match(r'^[0-9A-F]{5}\s+include\s+code[\\/]bank(\d\d)\.asm', line)
            if m: bank = int(m.group(1)); continue
            if re.match(r'^[0-9A-F]{5}\s+org\s+\$c000', line, re.I): bank = -1; continue
            m = re.match(r'^([0-9A-F]{5})\s+([A-Za-z_]\w*):', line)
            if not m: continue
            a, name = int(m.group(1), 16), m.group(2)
            if name in syms: continue
            if a < 0x800: syms[name] = (a, None)
            elif 0x8000 <= a < 0xC000 and bank is not None and bank >= 0: syms[name] = (a, bank)
            elif a >= 0xC000: syms[name] = (a, -1)
    code = os.path.join(src, 'code')
    for fn in sorted(os.listdir(code)) if os.path.isdir(code) else []:
        if not fn.endswith('.asm'): continue
        for line in open(os.path.join(code, fn), encoding='latin-1'):
            m = re.match(r'^\s*([A-Za-z_]\w*)\s*=\s*\$([0-9a-fA-F]+)\s*(;.*)?$', line)
            if m and m.group(1) not in syms:
                v = int(m.group(2), 16)
                if v < 0x800: syms[m.group(1)] = (v, None)
    return syms


def settings(src):
    """the build's switches (code/settings.default.asm, then code/settings.asm): NAME = value"""
    cfg = {}
    for fn in ('settings.default.asm', 'settings.asm'):
        p = os.path.join(src, 'code', fn)
        if not os.path.exists(p): continue
        for line in open(p, encoding='latin-1'):
            m = re.match(r'^\s*([A-Za-z_]\w*)\s*=\s*(\$[0-9a-fA-F]+|%[01]+|\d+)\s*(;.*)?$', line)
            if not m: continue
            v = m.group(2)
            cfg[m.group(1)] = int(v[1:], 16) if v[0] == '$' else int(v[1:], 2) if v[0] == '%' else int(v)
    return cfg


def main():
    os.makedirs(OUT, exist_ok=True)
    rom_p = os.path.join(SRC, 'SMBBase.nes')
    rom = read(rom_p) if os.path.exists(rom_p) else b''
    syms = symbols(SRC) if rom else {}
    cfg = settings(SRC) if rom else {}
    h = hashlib.sha1(rom + repr(sorted(syms.items())).encode() + repr(sorted(cfg.items())).encode()).hexdigest()
    stamp = os.path.join(OUT, 'smb1_rom.stamp')
    if os.path.exists(stamp) and read(stamp).decode() == h and os.path.exists(os.path.join(OUT, 'smb1_rom.c')):
        print('SMB1: up to date'); return 0
    missing = [n for n in NEEDED if n not in syms]
    if rom and missing: print('SMB1: missing from the listing: %s (no SMB1 Mario)' % ', '.join(missing)); rom = b''
    with open(os.path.join(OUT, 'smb1_rom.c'), 'w') as f:
        f.write('/* generated by tools/smb1_embed.py from %s - do not edit */\n#include <stdint.h>\n' % os.path.basename(rom_p))
        f.write('const uint32_t smb1_rom_size = %d;\nconst uint8_t smb1_rom[%d] = {\n' % (len(rom), max(len(rom), 1)))
        for i in range(0, len(rom), 32): f.write(','.join(str(b) for b in rom[i:i + 32]) + ',\n')
        if not rom: f.write('0\n')
        f.write('};\n')
    with open(os.path.join(OUT, 'smb1_syms.h'), 'w') as f:
        f.write('/* generated by tools/smb1_embed.py from SMB1Disassembly\'s listing and sources - do not edit */\n#pragma once\n')
        f.write('#define SMB1_HAVE_ROM %d\n' % (1 if rom else 0))
        for name, (a, bank) in sorted(syms.items()):
            f.write('#define SMB1_%s 0x%04X\n' % (name, a))
            if bank is not None: f.write('#define SMB1_%s_BANK %d\n' % (name, bank))
        for n in NEEDED:
            if n not in syms: f.write('#define SMB1_%s 0\n' % n)
        for name, v in sorted(cfg.items()): f.write('#define SMB1_CFG_%s %d\n' % (name, v))
    open(stamp, 'w').write(h)
    print('SMB1: %s (%d bytes), %d symbols' % (os.path.basename(rom_p), len(rom), len(syms)) if rom else 'SMB1: no ROM - SMB1 Mario not available')
    return 0


if __name__ == '__main__':
    sys.exit(main())
