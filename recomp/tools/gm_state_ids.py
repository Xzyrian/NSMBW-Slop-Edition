#!/usr/bin/env python3
"""Generate runtime/gm_state_ids.c and its section of runtime/hle_funcs.txt: every instance of
the sFStateVirtualID_c<T> / sFStateID_c<T> template functions (one set per class with states:
~486 classes) replaced by one native implementation (track B, instance 1).

An instance is recognised by its recompiled body: identical to the dEn_c instance once
addresses, labels and the getRootState it recurses into are normalised away. Kinds:
  init / exec / fini  initializeState / executeState / finalizeState (the PTMF call at +12/+24/+36)
  dtor / dtor2        ~sFStateVirtualID_c / ~sFStateID_c
  number              the root state's number()
  root                getRootState (recursive)
  name                isSameName
Run from recomp/ after tools/gen.sh has produced out/ (the hle list doesn't change the bodies the
script matches: it reads orig_ bodies too), then tools/gen.sh again."""
import re, glob, os, sys

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
os.chdir(ROOT)
BEGIN = '# track B (instance 1): state-ID templates (generated by tools/gm_state_ids.py - do not edit)'
END = '# end of state-ID templates'
# the dEn_c instance of each kind (gm_d_enemy_death.c used to have them by hand)
CANON = {0x800A27E0: 'init', 0x800A2810: 'exec', 0x800A2840: 'fini', 0x800A24D0: 'dtor',
         0x800A2530: 'dtor2', 0x800A2590: 'number', 0x800A2670: 'root', 0x800A2750: 'name'}

fn_re = re.compile(r'/\* (\S+) @ ([0-9A-F]+) size (0x[0-9a-f]+) \*/\nvoid ([^\n(]*)\([^\n]*\{\n(.*?)\n}\n', re.S)
funcs = {}   # addr -> (symbol, ident, size, body)
for f in sorted(glob.glob('out/recomp_[0-9]*.c')):
    for m in fn_re.finditer(open(f).read()):
        funcs[int(m.group(2), 16)] = (m.group(1), m.group(4), int(m.group(3), 16), m.group(5))
ident2addr = {v[1]: a for a, v in funcs.items()}
for a, v in list(funcs.items()):       # (an hle'd function's body is orig_<name>)
    if v[1].startswith('orig_'): ident2addr['hle_' + v[1][5:]] = a

call_re = re.compile(r'ctx->lr = 0x[0-9A-F]{8}u; (\w+)\(ctx, base\);')
def norm(body):
    """the body with addresses, labels and call targets other than library ones abstracted;
    returns (normalised text, [call targets])"""
    tg = []
    def sub_call(m):
        n = m.group(1)
        if n in ('hle_getID__12dStateBase_cFv', 'hle___dt__12dStateBase_cFv', '__dl__FPv_802B9280',
                 'strrchr_802E1C40', 'strcmp_802E1AB4', '__ptmf_scall_802DCBFC'):
            return 'CALL ' + n
        tg.append(n); return 'CALL X'
    b = call_re.sub(sub_call, body)
    b = re.sub(r'PPC_ENTER\(0x[0-9A-F]{8}u\)', 'PPC_ENTER(A)', b)
    b = re.sub(r'ctx->lr = 0x[0-9A-F]{8}u', 'ctx->lr = A', b)
    b = re.sub(r'L_8[0-9A-F]{7}', 'L', b)
    return b, tg

canon = {}
for a, k in CANON.items():
    canon[norm(funcs[a][3])[0]] = k
found = []   # (addr, symbol, kind, aux)
for a, (sym, ident, size, body) in sorted(funcs.items()):
    if a >= 0x81000000: continue            # (the 8-player module's own copies stay recompiled)
    nb, tg = norm(body)
    k = canon.get(nb)
    if not k: continue
    aux = 0
    if k in ('number', 'root'):
        if len(tg) != 1 or tg[0] not in ident2addr: continue
        aux = ident2addr[tg[0]]
    found.append((a, sym, k, aux))
roots = {a for a, _, k, _ in found if k == 'root'}
found = [x for x in found if x[2] not in ('number', 'root') or x[3] in roots]
# the hle name: the recompiled identifier without its _<address> suffix (fn_<address> stays;
# a REL's fn_1_1810_80769DF0 is fn_1_1810)
def hle_name(ident, a):
    if ident.startswith('orig_') or ident.startswith('hle_'): ident = ident.split('_', 1)[1]
    if ident != 'fn_%08X' % a and ident.endswith('_%08X' % a): ident = ident[:-9]
    return ident
# the recompiler replaces every function with a listed name: a name must only stand for copies
# of the same kind (and the same getRootState)
byname = {}
for a, (sym, ident, size, body) in funcs.items(): byname.setdefault(hle_name(ident, a), []).append(a)
call_of = {a: (k, aux) for a, _, k, aux in found}
ok = []
for a, sym, k, aux in found:
    n = hle_name(funcs[a][1], a)
    if all(b in call_of and call_of[b] == (k, aux) for b in byname[n]): ok.append((a, n, k, aux))
dropped = len(found) - len(ok)
found = sorted({n: (a, n, k, aux) for a, n, k, aux in ok}.values())
print('dropped (name shared with something else):', dropped)
counts = {}
for x in found: counts[x[2]] = counts.get(x[2], 0) + 1
print('state-ID template instances:', len(found), counts)

KIND = {'init': 'st_call(GM_PASS, 12, 0x%08Xu)', 'exec': 'st_call(GM_PASS, 24, 0x%08Xu)', 'fini': 'st_call(GM_PASS, 36, 0x%08Xu)',
        'dtor': 'GM_RET(st_dtor(GM_PASS, 0x%08Xu, 0))', 'dtor2': 'GM_RET(st_dtor(GM_PASS, 0x%08Xu, 1))',
        'number': 'GM_RET(st_number(GM_PASS, 0x%08Xu, 0x%08Xu))', 'root': 'GM_RET(st_root(GM_PASS, 0x%08Xu, 0x%08Xu))',
        'name': 'GM_RET(st_same_name(GM_PASS, 0x%08Xu))'}     # (the copy's own address: its calls' return addresses)
out = ['/* gm_state_ids.c - GENERATED by tools/gm_state_ids.py from out/: do not edit the entries.',
       ' * The sFStateVirtualID_c<T> / sFStateID_c<T> template functions (s_StateID.hpp): every class',
       ' * with states has its own copy of these 8, %d in all, identical but for the getRootState' % len(found),
       ' * they recurse into. One native implementation (gm_state_ids_impl.h), one entry per copy.',
       ' * Track B (gm.h, docs/DECOMP.md), instance 1. */',
       '#include "gm_state_ids_impl.h"', '']
for a, sym, k, aux in found:
    call = KIND[k] % ((a, aux) if k in ('number', 'root') else (a,))
    out.append('GM_HLE(%s) { %s; }' % (sym, call))
open('runtime/gm_state_ids.c', 'w').write('\n'.join(out) + '\n')

h = open('runtime/hle_funcs.txt').read()
sec = BEGIN + '\n' + '\n'.join(n for _, n, _, _ in found) + '\n' + END + '\n'
if BEGIN in h:
    i = h.index(BEGIN); j = h.index(END, i) + len(END) + 1
    h = h[:i] + sec + h[j:]
else:
    h = h.rstrip('\n') + '\n' + sec
open('runtime/hle_funcs.txt', 'w').write(h)
